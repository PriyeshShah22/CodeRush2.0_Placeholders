const dictionaries: Record<Exclude<UiLocale, "en">, Record<string, string>> = { hi, mr };

export function translateUi(locale: UiLocale, source: string, variables: Variables = {}) {
  const template = locale === "en" ? source : dictionaries[locale][source] ?? source;
  return Object.entries(variables).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

